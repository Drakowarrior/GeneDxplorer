from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field

class CitationRecord(BaseModel):
    citation_id: str = Field(..., description="Unique citation identifier")
    source: str = Field(..., description="Source database name, e.g. NCBI MedGen, NCBI ClinVar")
    record_id: str = Field(..., description="Record UID or Variation ID")
    title: Optional[str] = Field(None, description="Record title or concept name")
    evidence_type: str = Field("Direct Annotation", description="Type of evidence")
    gene_symbol: Optional[str] = Field(None, description="Associated gene symbol")
    disease_title: Optional[str] = Field(None, description="Associated disease title")
    clinical_significance: Optional[str] = Field(None, description="ClinVar clinical significance if applicable")
    review_status: Optional[str] = Field(None, description="ClinVar review status if applicable")
    official_url: str = Field(..., description="Official NCBI URL for tracing evidence")
    retrieved_at: str = Field(..., description="ISO UTC timestamp when retrieved")

class ReproducibilityManifest(BaseModel):
    manifest_id: str = Field(..., description="Unique manifest ID")
    created_at: str = Field(..., description="ISO UTC timestamp of creation")
    software_version: str = Field(..., description="GeneDxplorer software version")
    analysis_schema_version: int = Field(1, description="Schema version of analysis engine")
    snapshot_schema_version: int = Field(1, description="Schema version of snapshot payload")
    report_id: Optional[str] = Field(None, description="Associated research report ID if available")
    report_type: str = Field(..., description="Type of report/analysis")
    query: str = Field(..., description="Primary query string")
    search_strategy: str = Field(..., description="NCBI search strategy")
    source_providers: List[str] = Field(default_factory=list, description="Active evidence source providers")
    records_available: int = Field(0, description="Total matching records available at NCBI")
    records_retrieved: int = Field(0, description="Total records retrieved")
    records_analyzed: int = Field(0, description="Total records analyzed")
    analysis_limit: int = Field(500, description="Configured retrieval limit")
    retrieval_timestamp: str = Field(..., description="ISO UTC timestamp of original data retrieval")
    analysis_parameters: Dict[str, Any] = Field(default_factory=dict, description="Execution parameters")
    source_record_ids: List[str] = Field(default_factory=list, description="List of analyzed MedGen UIDs / ClinVar IDs")
    gene_ids: List[str] = Field(default_factory=list, description="NCBI Gene IDs identified")
    disease_concepts: List[str] = Field(default_factory=list, description="Concept IDs identified")
    calculation_method: str = Field("Deterministic frequency & set-theoretic overlap", description="Mathematical method description")
    export_formats: List[str] = Field(default_factory=lambda: ["json", "csv", "zip", "publication_csv"])
    snapshot_hash: str = Field(..., description="Canonical SHA-256 hash of snapshot payload")
    python_version: str = Field(..., description="Python runtime version")
    platform: str = Field(..., description="Operating system platform")

class AnalysisSnapshot(BaseModel):
    snapshot_id: str = Field(..., description="Unique snapshot identifier")
    snapshot_hash: str = Field(..., description="Canonical SHA-256 hash of scientific payload")
    created_at: str = Field(..., description="ISO UTC creation timestamp")
    software_version: str = Field(..., description="GeneDxplorer software version")
    report_id: Optional[str] = Field(None, description="Associated research report ID")
    report_type: str = Field(..., description="Report type, e.g. disease, gene, comparison, similarity, graph, workspace")
    source: str = Field("NCBI MedGen", description="Data source name")
    query: str = Field(..., description="Analysis query")
    search_strategy: str = Field(..., description="Search strategy used")
    parameters: Dict[str, Any] = Field(default_factory=dict, description="Parameters used during analysis")
    records: List[Dict[str, Any]] = Field(default_factory=list, description="Analyzed records metadata")
    gene_associations: List[Dict[str, Any]] = Field(default_factory=list, description="Normalized reported gene associations")
    evidence: List[Dict[str, Any]] = Field(default_factory=list, description="Supporting evidence items")
    analysis_results: Dict[str, Any] = Field(default_factory=dict, description="Raw or aggregated numerical analysis results")
    user_notes: List[Dict[str, Any]] = Field(default_factory=list, description="Explicitly labeled user research notes")
    provenance: Dict[str, Any] = Field(default_factory=dict, description="Provenance and metadata audit trail")
